"""Regenerate and kernel-check the archived barium through neodymium certificates."""
import argparse
import csv
import gzip
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
from decimal import Decimal
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parents[1]
ARCHIVE = PAPER.parents[1] / "data/element_thresholds_20261011.json.gz"
ARCHIVE_SHA256 = "75e67478d9a22ef85fa2d3f6ac36ad2860c6f8f62215127c558438a2cb53f62c"
NAMES = ["Barium", "Lanthanum", "Cerium", "Praseodymium", "Neodymium"]
# Ning & Lu (2022), Table 3, transcribed in the batch's shared affinity table.
AFFINITY_PATH = HERE.parent/"ladder/affinities.csv"


def read_affinities():
    with AFFINITY_PATH.open(newline="") as f:
        rows = list(csv.DictReader(f))
    if [int(row["Z"]) for row in rows] != list(range(56,61)):
        raise ValueError("Unexpected affinity inputs")
    return {name: (r["EA_eV"], r["unc_eV"]) for name,r in zip(NAMES,rows)}


def number(x):
    return format(Decimal(x), "f")


def read_archive():
    raw = ARCHIVE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != ARCHIVE_SHA256:
        raise ValueError("Pinned threshold archive hash mismatch")
    book = json.loads(gzip.decompress(raw), parse_float=Decimal)["records"]
    result = {}
    for z, name in enumerate(NAMES, 56):
        row = book[z - 1]
        if row["Z"] != z or row["name"] != name:
            raise ValueError(f"Wrong record at Z={z}")
        series = row["thresholds"]
        if [r["q"] for r in series] != list(range(z)):
            raise ValueError(f"Missing, duplicated or unordered q at Z={z}")
        result[name] = [(number(r["IE_eV"]), number(r["unc_eV"])) for r in series]
    return result


def generate(series, affinities):
    text = [
        "-- Generated by verify.py from the pinned product; energies and absolute uncertainties in eV.",
        "import Batch12Bounds", "", "namespace ElementPaper.Batch12", "",
        "open VOTKP.NearestPair", "set_option maxRecDepth 16384",
        "set_option maxHeartbeats 10000000", "",
    ]
    audits = ["ratioBounds", "interiorForEveryRealization", "exteriorForEveryRealization",
              "strictRankForEveryRealization"]
    for z, name in enumerate(NAMES, 56):
        literals = [f"({v}, {u})" for v, u in series[name]]
        groups = [", ".join(literals[i:i+4]) for i in range(0, len(literals), 4)]
        ea, unc = affinities[name]
        text.extend([
            f"def {name} : List Reading :=", "  [" + ",\n   ".join(groups) + "]",
            f"def {name}Affinity : Reading := ({ea}, {unc})", "",
            f"theorem {name}OrdinaryBoxes : {name}.length = {z} ∧",
            f"    (faces {name}).length = {z-1} ∧ (faces {name}).all admitsInside = true ∧",
            f"    (faces {name}).all (fun f => decide (1 ≤ endpointLo f ∧ endpointHi f < 4.1)) = true ∧",
            f"    tiesForward {name} = " + ("[10]" if name == "Neodymium" else "[]") + " := by decide +kernel",
            "",
            f"theorem {name}Highest : ranked (nonKFaces {name} {z}) (kFace {name} {z}) = true := by",
            "  decide +kernel", "",
            f"theorem {name}Anion :",
            f"    let f := face {name}Affinity {name}[0]!",
            "    admitsOutside f = true ∧ chemistryOutside f = true ∧ Batch11.silicon < endpointLo f := by",
            "  decide +kernel", "",
        ])
        audits.extend([name+"OrdinaryBoxes", name+"Highest", name+"Anion"])
    text.extend([
        "def ordinary := [" + ", ".join(NAMES) + "].flatMap centralPairs",
        "def throughNeodymium := Batch11.expanded ++ ordinary", "",
        "theorem batchOrdinaryCounts : ordinary.length = 285 ∧ throughNeodymium.length = 1770 := by",
        "  decide +kernel", "",
        "theorem batchOrdinaryBelowNitrogen : ordinary.all (fun p =>",
        "    decide (p.2/p.1 ≤ Batch11.nitrogen) && !Batch11.outside p.1 p.2) = true := by",
        "  decide +kernel", "",
        "theorem windowHydrogenNeodymium (c : Rat) : Batch11.Fits throughNeodymium c ↔",
        "    Batch11.nitrogen ≤ c ∧ c < Batch11.cesium := by",
        "  constructor",
        "  · intro h",
        "    apply (Batch11.windowHydrogenCesium c).mp",
        "    intro p hp",
        "    exact h p (List.mem_append_left ordinary hp)",
        "  · rintro ⟨hl, hu⟩ p hp",
        "    rcases List.mem_append.mp hp with old | newrow",
        "    · exact (Batch11.windowHydrogenCesium c).mpr ⟨hl,hu⟩ p old",
        "    · have h := List.all_eq_true.mp batchOrdinaryBelowNitrogen p newrow",
        "      simp at h",
        "      rw [h.2]",
        "      exact decide_eq_false (by grind)", "",
        "theorem heliumCoreOrder :",
    ])
    comparisons = [
        f"pHi (kFace {b} {z + 1}) < pLo (kFace {a} {z})"
        for z,(a,b) in enumerate(zip(NAMES,NAMES[1:]), 56)]
    text.extend(["    " + " ∧\n    ".join(comparisons) + " := by decide +kernel", "",
                 "/-- Nd k=10: the two T-grade intervals meet at 160 eV. -/",
                 "theorem neodymiumTouchingBoxes :",
                 "    let f := face Neodymium[9]! Neodymium[10]!",
                 "    Admits f 160 160 ∧ endpointLo f = 1 ∧ g 160 160 = 0 ∧",
                 "    g f.a f.b = 1/20 ∧ admitsInside f = true := by",
                 "  dsimp [Admits]", "  decide +kernel", ""])
    text.extend([
        "/-- Use the already checked cesium series, where index 0 is its electron affinity. -/",
        "def priorCesium54 : Face :=",
        "  let a := Batch11.Cesium[1]!.get!",
        "  let b := Batch11.Cesium[2]!.get!",
        "  face (a.e, a.unc.get!) (b.e, b.unc.get!)", "",
        "/-- The 54-electron middle ion: k=Z−54, independent of orbital identity. -/",
        "def atCount54 (xs : List Reading) (z : Nat) : Face :=",
        "  face (xs[z-55]!) (xs[z-54]!)", "",
        "def channel54 : List Face := [priorCesium54,",
        "  " + ", ".join(f"atCount54 {name} {z}" for z,name in enumerate(NAMES,56)) + "]", "",
        "theorem channel54Descends :",
        "    channel54.length = 6 ∧ channel54.all valid = true ∧",
        "    (channel54.zip channel54.tail).all (fun (a,b) =>",
        "      decide (endpointHi b < endpointLo a)) = true := by decide +kernel", "",
        "/-- Three explicit admitted witnesses below, on and above the nominal comparison. -/",
        "theorem praseodymiumStraddles :",
        "    let f := atCount54 Praseodymium 59",
        "    let s := (36:Rat)/25",
        "    f.b/f.a < s ∧ endpointLo f < s ∧ s < endpointHi f ∧",
        "    Admits f 57.53 78 ∧ (78:Rat)/57.53 < s ∧",
        "    Admits f 57.53 82.8432 ∧ (82.8432:Rat)/57.53 = s ∧",
        "    Admits f 57.53 86 ∧ s < (86:Rat)/57.53 := by",
        "  dsimp [Admits]", "  decide +kernel", "",
        "theorem neodymiumBelowNominal {a b : Rat} (h : Admits (atCount54 Neodymium 60) a b) :",
        "    b/a < 36/25 := by",
        "  have v : valid (atCount54 Neodymium 60) = true := by decide +kernel",
        "  have m : endpointHi (atCount54 Neodymium 60) < 36/25 := by decide +kernel",
        "  have hi := (ratioBounds v h).2", "  grind", "",
    ])
    audits.extend(["channel54Descends","praseodymiumStraddles","neodymiumBelowNominal"])
    audits.extend(["batchOrdinaryCounts", "batchOrdinaryBelowNitrogen", "windowHydrogenNeodymium",
                   "heliumCoreOrder", "neodymiumTouchingBoxes"])
    text.extend(["#print axioms " + t for t in audits])
    text.extend(["", "end ElementPaper.Batch12", ""])
    return "\n".join(text), audits


def independent_reparse(source):
    # Different parser, numeric type and data extraction path from the generator above.
    book = json.loads(gzip.decompress(ARCHIVE.read_bytes()), parse_float=Fraction)["records"]
    count = 0
    for z, name in enumerate(NAMES, 56):
        section = re.search(rf"def {name} : List Reading :=\s*\[(.*?)\]", source, re.S)[1]
        got = [(Fraction(a),Fraction(b)) for a,b in re.findall(r"\(([\d.]+), ([\d.]+)\)", section)]
        want = [(r["IE_eV"],r["unc_eV"]) for r in book[z-1]["thresholds"]]
        if got != want:
            raise ValueError(f"{name} emitted list differs from archive")
        count += len(got)
    return count


def verify_csv(path, data, affinities):
    with path.open(newline="") as f:
        rows = list(csv.DictReader(f))
    if [(int(r["Z"]), int(r["k"])) for r in rows] != [
            (z,k) for z in range(56,61) for k in range(z+1)]:
        raise ValueError("Published CSV does not have the expected Z,k keys")
    for r in rows:
        z,k = int(r["Z"]),int(r["k"])
        name = NAMES[z-56]
        wanted = data[name][k-1][0] if k else affinities[name][0]
        if k == z:
            if (r["z_k"], r["Gamma_k"]) != ("",""):
                raise ValueError(f"Unexpected terminal ratio for {name}")
        else:
            a,b = Fraction(wanted), Fraction(data[name][k][0])
            for field, raw in [("z_k", b/a), ("Gamma_k", (b-a)/(b+a))]:
                if Fraction(r[field]) != round(raw,6):
                    raise ValueError(f"Published {field} mismatch at Z={z}, k={k}")
        if Fraction(r["IE_k (eV)"]) != Fraction(wanted):
            raise ValueError(f"Published CSV mismatch at Z={z}, k={k}")
    return len(rows)


def lean_run(lean, audits):
    cmd = [lean, "-j1"]
    sources = [
        PAPER / "batch10/nearest_lean/MarginBounds.lean",
        PAPER / "batch11/lean/Batch11Kernel.lean",
        PAPER / "batch11/lean/AntimonyCesium.lean",
        HERE / "Batch12Bounds.lean", HERE / "BariumNeodymium.lean",
    ]
    print(subprocess.check_output([lean,"--version"], text=True).rstrip(), flush=True)
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        env = dict(os.environ, LEAN_PATH=td)
        for source in sources:
            shutil.copy2(source, tmp/source.name)
            run = subprocess.run(cmd + ["-o", source.stem+".olean",source.name],
                                 cwd=tmp, env=env, capture_output=True, text=True)
            if run.returncode:
                raise RuntimeError(run.stdout + run.stderr)
        for name in audits:
            fullname = "ElementPaper.Batch12." + name
            matches = [line for line in run.stdout.splitlines() if line.startswith("'" + fullname + "'")]
            if len(matches)!=1:
                raise RuntimeError(f"Missing or repeated audit output for {name}")
            line = matches[0]
            if "does not depend on any axioms" not in line:
                axioms = re.fullmatch(r".*depends on axioms: \[([^\]]*)\]", line)
                if not axioms or set(axioms[1].split(", ")) - {"propext","Classical.choice","Quot.sound"}:
                    raise RuntimeError(line)
            print(line)
        # Each bad claim must fail because kernel reduction proves its negation.
        controls = {
            "Every neodymium ratio box is strictly forward": "tiesForward Neodymium = []",
            "36/25 is a lower floor for neodymium at 54 electrons":
                "(36:Rat)/25 ≤ endpointLo (atCount54 Neodymium 60)",
            "Every praseodymium realization is below 36/25":
                "endpointHi (atCount54 Praseodymium 59) < 36/25",
            "Barium anion box lies inside": "admitsInside (face BariumAffinity Barium[0]!) = true",
            "Barium valence opening outranks its helium-core opening":
                "VOTKP.NearestPair.pHi (kFace Barium 56) < VOTKP.NearestPair.pLo (face Barium[1]! Barium[2]!)",
        }
        for label, statement in controls.items():
            (tmp/"Control.lean").write_text(
                f"import BariumNeodymium\nopen ElementPaper.Batch12\nexample : {statement} := by decide +kernel\n")
            bad = subprocess.run(cmd+["Control.lean"], cwd=tmp,env=env,capture_output=True,text=True)
            if bad.returncode==0 or "error: Tactic `decide`" not in bad.stdout:
                raise RuntimeError(f"Inconclusive negative control: {label}\n{bad.stdout}{bad.stderr}")
            print("Rejected: " + label)
    print(f"{len(audits)} theorem audits passed. Five false controls rejected.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate",action="store_true")
    parser.add_argument("--csv", type=Path, default=HERE.parent/"ladder/batch12_ba_nd.csv")
    parser.add_argument("--lean",default="lean")
    args = parser.parse_args()
    data = read_archive()
    affinities = read_affinities()
    source, audits = generate(data, affinities)
    target = HERE/"BariumNeodymium.lean"
    if args.generate:
        target.write_text(source)
    if target.read_text()!=source:
        raise ValueError("Committed certificate differs from regenerated source")
    print(f"{independent_reparse(target.read_text())} ordinary energies and their uncertainty fields agree with SHA-256 {ARCHIVE_SHA256}.")
    if args.csv:
        print(f"{verify_csv(args.csv,data,affinities)} serialized energy fields agree (including five affinities); all 290 z and Gamma pairs match independently at six places.")
    lean_run(args.lean, audits)


if __name__ == "__main__":
    main()
