ARCHIVE_SHA = "75e67478d9a22ef85fa2d3f6ac36ad2860c6f8f62215127c558438a2cb53f62c"
OLD_AFFINITY = PAPER/"batch10/robust/affinities_h_sn.csv"
OLD_AFFINITY_SHA = "ed044bc7e5dcb51d23b8fa8a7845c4ccecc0156c3ea9534e90f1d3ddf58af1c2"
B11_CSV = PAPER/"batch11/ladder/batch11_rungs_detailed.csv"
