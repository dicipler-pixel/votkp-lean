WAVENUMBER = F("6.62607015e-34")*299792458*100/F("1.602176634e-19")
B11_NAMES = ["Antimony","Tellurium","Iodine","Xenon","Cesium"]
B12_NAMES = ["Barium","Lanthanum","Cerium","Praseodymium","Neodymium"]


def csv_rows(path):
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def optional_frac(s):
    return None if s in ("",None) else F(s)


def archive_book():
    raw = ARCHIVE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != ARCHIVE_SHA:
        raise ValueError("Threshold archive hash differs")
    atoms = json.loads(gzip.decompress(raw),parse_float=Decimal)["records"][:60]
    if [r["Z"] for r in atoms] != list(range(1,61)):
        raise ValueError("The first sixty element keys are incomplete")
    for r in atoms:
        if [t["q"] for t in r["thresholds"]] != list(range(r["Z"])):
            raise ValueError(f"Missing ion charge in {r['symbol']}")
    return atoms


def affinities():
    aff = {}
    if hashlib.sha256(OLD_AFFINITY.read_bytes()).hexdigest() != OLD_AFFINITY_SHA:
        raise ValueError("Previous H–Sn affinities changed")
    old = csv_rows(OLD_AFFINITY)
    for row in old:
        if row["status"] == "unbound":
            continue
        scale = WAVENUMBER if row["source"] == "Se26_cm-1" else 1
        unc = optional_frac(row["unc_source_units"])
        aff[int(row["Z"])] = F(row["EA_source_units"])*scale, None if unc is None else unc*scale
    for row in csv_rows(B11_CSV):
        if row["k"] == "0":
            aff[int(row["Z"])] = F(row["start_eV"]), optional_frac(row["start_unc_eV"])
    for row in csv_rows(B12_AFFINITY):
        aff[int(row["Z"])] = F(row["EA_eV"]), F(row["unc_eV"])
    return aff


def independent_statistics(atoms, aff):
    rows = []
    for atom in atoms:
        z = atom["Z"]
        levels = [aff.get(z)] + [(F(r["IE_eV"]),optional_frac(r["unc_eV"])) for r in atom["thresholds"]]
        for k,(a,b) in enumerate(zip(levels,levels[1:])):
            if a is None:
                continue
            x,dx = a
            y,dy = b
            label = 2*(y-x)**2 > (y+x)**2
            lo = hi = None
            if dx is not None and dy is not None:
                if min(dx,dy)<0 or min(x-dx,y-dy)<=0:
                    raise ValueError("Negative uncertainty or nonpositive input range")
                lo,hi = (y-dy)/(x+dx), (y+dy)/(x-dx)
                # Strict bounds for squared reflection over both sides of z=1.
                gl,gu = (lo-1)/(lo+1), (hi-1)/(hi+1)
                p_lo = 0 if gl<=0<=gu else min(gl*gl,gu*gu)
                p_hi = max(gl*gl,gu*gu)
                if not (p_lo>F(1,2) if label else p_hi<F(1,2)):
                    raise ValueError(f"Squared wall unstable inside reported box Z={z}, k={k}")
            rows.append((z,k,y/x,lo,hi,label))
    gaps = [(z,k) for z,k,_,lo,_,_ in rows if lo is None]
    bounds = {}
    for ordinary in [False,True]:
        for mode in ["central","box"]:
            group = [r for r in rows if (not ordinary or r[1]!=0) and (mode=="central" or r[3] is not None)]
            inside = max((r for r in group if not r[5]),key=lambda r: r[2] if mode=="central" else r[4])
            outside = min((r for r in group if r[5]),key=lambda r: r[2] if mode=="central" else r[3])
            bounds[ordinary,mode] = (len(group),inside,outside)
    return rows, gaps, bounds


def frac_lit(x):
    return str(x.numerator) if x.denominator==1 else f"({x.numerator}/{x.denominator})"


def opt_lit(x):
    return "none" if x is None else "some "+frac_lit(x)


def chunks(values, n):
    return [values[i:i+n] for i in range(0,len(values),n)]


def source(atoms,aff,rows,gaps,bounds):
    out = ["-- Generated by verify_window.py. Uncertainties below are in eV.",
           "import WindowKernel", "", "namespace ElementPaper.Batch12.Window",
           "open ElementPaper.Batch11 (Energy)", "set_option maxRecDepth 16384",
           "set_option maxHeartbeats 40000000", ""]
    for group in chunks(atoms[:50],10):
        high = group[-1]["Z"]
        out.append(f"def widthsThrough{high} : List (List (Option Rat)) :=")
        brackets = []
        for atom in group:
            vals = ["none" if q["unc_eV"] is None else "some "+format(Decimal(q["unc_eV"]),"f")
                    for q in atom["thresholds"]]
            brackets.append("["+", ".join(vals)+"]")
        out.extend(["  ["+",\n   ".join(brackets)+"]",""])
    eas = []
    for z in range(1,51):
        if z not in aff:
            eas.append("none")
        else:
            ea,unc = aff[z]
            eas.append(f"some ⟨{frac_lit(ea)}, {opt_lit(unc)}⟩")
    out.extend(["def olderAffinities : List (Option Energy) :=",
                "  ["+",\n   ".join(", ".join(part) for part in chunks(eas,4))+"]", "",
                "def olderValues := "+" ++ ".join("Batch11.priorThrough"+str(z) for z in range(10,51,10)),
                "def olderWidths := "+" ++ ".join("widthsThrough"+str(z) for z in range(10,51,10)),
                "def olderAtoms := ((olderAffinities.zip olderValues).zip olderWidths).map",
                "  (fun ((ea,ies),ws) => oldAtom ea ies ws)", "",
                "def atomTables : List (List (Option Energy)) := olderAtoms ++",
                "  ["+", ".join("Batch11."+name for name in B11_NAMES)+"] ++",
                "  ["+",\n   ".join("ofReadings "+name+"Affinity "+name for name in B12_NAMES)+"]", "",
                "def allRungs := rungs atomTables",
                "def ordinaryRungs := allRungs.filter (fun r => r.k != 0)",
                "def central := allRungs.map point",
                "def complete := allRungs.filterMap box",
                "def ordinaryComplete := ordinaryRungs.filterMap box", "",
                "def atRung (z k : Nat) : Rung :=",
                "  let es := atomTables[z-1]!",
                "  ⟨z,k,es[k]!.get!, es[k+1]!.get!⟩", "",
                "def silver := atRung 47 0", "def silicon := atRung 14 0",
                "def nitrogen := atRung 7 5", "def caesium := atRung 55 1", "",
                "theorem historySourcesAlign :",
                "    (olderValues.map List.length) = (olderWidths.map List.length) ∧",
                "    atomTables.length = 60 ∧",
                "    (atomTables.zipIdx).all (fun (es,i) => decide (es.length = i+2)) = true := by",
                "  decide +kernel", "",
                "theorem countLedgerAndCalls :",
                f"    central.length = {len(rows)} ∧ complete.length = {len(rows)-len(gaps)} ∧",
                f"    ordinaryRungs.length = {bounds[True,'central'][0]} ∧ ordinaryComplete.length = {bounds[True,'box'][0]} ∧",
                f"    (central.filter Range.outside).length = {sum(1 for r in rows if r[5])} ∧",
                f"    (ordinaryRungs.filter (fun r => (point r).outside)).length = {sum(1 for r in rows if r[1] and r[5])} := by",
                "  decide +kernel", "",
                "theorem missingBoxKeys :",
                "    (allRungs.filter (fun r => (face? r).isNone)).map (fun r => (r.z,r.k)) =",
                "    [" + ", ".join(f"({z},{k})" for z,k in gaps)+"] := by decide +kernel","",
                "theorem stableOnAllReportedBoxes : allRungs.all stable = true := by decide +kernel", ""])
    out.extend([
        "theorem uniqueForwardContact :",
        "    complete.all (fun row => decide (1 ≤ row.lo)) = true ∧",
        "    allRungs.filterMap (fun r => do",
        "      let row ← box r",
        "      if row.lo ≤ 1 then some (r.z,r.k) else none) = [(60,10)] := by",
        "  decide +kernel", "",
    ])
    audits = ["uniqueForwardContact", "sharpRangeWindow","stabilityMeaning","historySourcesAlign","countLedgerAndCalls",
              "missingBoxKeys","stableOnAllReportedBoxes"]
    for title, ledger, left, right, mode in [
            ("centralWindowAll", "central", "silver", "silicon", "central"),
            ("boxWindowAll","complete","silver","silicon","box"),
            ("boxWindowOrdinary","ordinaryComplete","nitrogen","caesium","box")]:
        def facet(name):
            return f"(point {name})" if mode=="central" else f"((box {name}).get!)"
        p,q = facet(left),facet(right)
        witness = bounds[ledger=="ordinaryComplete", mode]
        lo = witness[1][2 if mode=="central" else 4]
        hi = witness[2][2 if mode=="central" else 3]
        out.extend([
            f"theorem {title} (c : Rat) : Fits {ledger} c ↔",
            f"    {frac_lit(lo)} ≤ c ∧ c < {frac_lit(hi)} := by",
            f"  have h := sharpRangeWindow {ledger} {p} {q}",
            "    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)",
            "    (by decide +kernel) c",
            f"  have l : {p}.hi = {frac_lit(lo)} := by decide +kernel",
            f"  have u : {q}.lo = {frac_lit(hi)} := by decide +kernel",
            "  rw [l,u] at h", "  exact h",""])
        audits.append(title)
    out.extend([
        "theorem alternativeCutoffs : Fits complete 5.82 ∧ Fits complete 5.83 ∧ Fits complete 5.85 ∧",
        "    ¬ Fits complete 5.8 ∧ ¬ Fits complete 5.9 := by",
        "  simp only [boxWindowAll]", "  decide +kernel", "",
    ])
    audits.append("alternativeCutoffs")
    out.extend(["#print axioms "+name for name in audits])
    out.extend(["", "end ElementPaper.Batch12.Window",""])
    return "\n".join(out), audits


def reparse_old_widths(s, atoms):
    sections = re.findall(r"def widthsThrough\d+ : List \(List \(Option Rat\)\) :=\s*(.*?)\n\n",s,re.S)
    lists = []
    for section in sections:
        for segment in re.findall(r"\[([^\[\]]+)\]",section):
            fields = segment.split(", ")
            lists.append([None if f=="none" else F(f.removeprefix("some ")) for f in fields])
    want = [[optional_frac(q["unc_eV"]) for q in rec["thresholds"]] for rec in atoms[:50]]
    if lists!=want:
        raise ValueError("Lean optional uncertainty literals differ from archive")


def reparse_inherited_energies(atoms, aff):
    previous = (PAPER/"batch11/lean/AntimonyCesium.lean").read_text()
    for zmax in range(10,51,10):
        section = re.search(rf"def priorThrough{zmax} : List \(List Rat\) :=\s*(.*?)\n\ntheorem",previous,re.S)[1]
        rows = [[F(v.strip()) for v in s.split(",")] for s in re.findall(r"\[([^\[\]]+)\]",section)]
        expected = [[F(t["IE_eV"]) for t in a["thresholds"]] for a in atoms[zmax-10:zmax]]
        if rows!=expected:
            raise ValueError(f"Imported priorThrough{zmax} energies differ")
    b12 = (BATCH/"BariumNeodymium.lean").read_text()
    for z in range(51,61):
        if z<=55:
            name=B11_NAMES[z-51]
            expr=rf"def {name} : List \(Option Energy\) :=\s*\[(.*?)\]"
            enc=re.findall(r"some ⟨([^,]+),(?:\(some ([^)]+)\)|(none))⟩",re.search(expr,previous,re.S)[1])
            ies=[(F(v),F(u) if u else None) for v,u,_ in enc]
            if name!="Xenon":
                if ies[0]!=aff[z]:
                    raise ValueError(f"Imported {name} affinity/uncertainty mismatch")
                ies=ies[1:]
            elif z in aff or not re.search(r"^\s*none,",re.search(expr,previous,re.S)[1]):
                raise ValueError("Xenon unexpectedly has an affinity")
        else:
            name=B12_NAMES[z-56]
            expr=rf"def {name} : List Reading :=\s*\[(.*?)\]"
            ea=re.search(rf"def {name}Affinity : Reading := \(([\d.]+), ([\d.]+)\)",b12)
            if (F(ea[1]),F(ea[2]))!=aff[z]:
                raise ValueError(f"Imported {name} affinity/uncertainty mismatch")
            ies=[(F(v),F(u)) for v,u in re.findall(r"\(([\d.]+), ([\d.]+)\)",re.search(expr,b12,re.S)[1])]
        if ies!=[(F(t["IE_eV"]),optional_frac(t["unc_eV"])) for t in atoms[z-1]["thresholds"]]:
            raise ValueError(f"Imported {name} energy/uncertainty mismatch")


def run(lean, audits):
    files = [
        PAPER/"batch10/nearest_lean/MarginBounds.lean", PAPER/"batch11/lean/Batch11Kernel.lean",
        PAPER/"batch11/lean/AntimonyCesium.lean", BATCH/"Batch12Bounds.lean", BATCH/"BariumNeodymium.lean",
        HERE/"WindowKernel.lean", HERE/"WindowThroughNeodymium.lean",
    ]
    print(subprocess.check_output([lean,"--version"],text=True).strip(),flush=True)
    with tempfile.TemporaryDirectory() as td:
        tmp=Path(td)
        env=dict(os.environ,LEAN_PATH=td)
        for p in files:
            shutil.copyfile(p,tmp/p.name)
            proof=subprocess.run([lean,"-j1","-o",p.stem+".olean",p.name],cwd=tmp,env=env,
                                 capture_output=True,text=True)
            if proof.returncode:
                raise RuntimeError(proof.stdout+proof.stderr)
        for name in audits:
            tag = "'ElementPaper.Batch12.Window."+name+"'"
            matches = [line for line in proof.stdout.splitlines() if line.startswith(tag)]
            if len(matches)!=1:
                raise RuntimeError(f"Missing axiom output for {name}")
            line=matches[0]
            if "does not depend on any axioms" not in line:
                match=re.fullmatch(r".*depends on axioms: \[([^\]]*)\]",line)
                if not match or set(match[1].split(", "))-{"propext","Classical.choice","Quot.sound"}:
                    raise RuntimeError(line)
            print(line)
        # A cutoff at the rational lower endpoint fits; a cutoff at the upper endpoint does not.
        for label,theorem,endpoint,wrong in [
                ("upper endpoint fits","boxWindowAll","6270500/1068863",""),
                ("lower endpoint fails","boxWindowAll","7576259/1304450","¬ ")]:
            control=(f"import WindowThroughNeodymium\nopen ElementPaper.Batch12.Window\n"
                     f"example : {wrong}Fits complete ({endpoint}) := by\n  rw [{theorem}]\n  decide +kernel\n")
            (tmp/"FalseControl.lean").write_text(control)
            out=subprocess.run([lean,"-j1","FalseControl.lean"],cwd=tmp,env=env,text=True,capture_output=True)
            if out.returncode==0 or "error: Tactic `decide`" not in out.stdout:
                raise RuntimeError("Inconclusive false control\n"+out.stdout+out.stderr)
            print("Rejected false claim: "+label)
    print(f"{len(audits)} theorem audits passed. Two endpoint controls rejected.")


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate",action="store_true")
    parser.add_argument("--lean",default="lean")
    args=parser.parse_args()
    atoms=archive_book()
    aff=affinities()
    rows,gaps,bounds=independent_statistics(atoms,aff)
    s,audits=source(atoms,aff,rows,gaps,bounds)
    p=HERE/"WindowThroughNeodymium.lean"
    if args.generate:
        p.write_text(s)
    if s!=p.read_text():
        raise ValueError("Regenerated window certificate differs")
    reparse_old_widths(s,atoms)
    reparse_inherited_energies(atoms,aff)
    older_list=re.search(r"def olderAffinities : List \(Option Energy\) :=\s*\[(.*?)\]",s,re.S)[1]
    option_rows=[x.strip() for x in re.findall(r"none(?=,|\s*$)|some ⟨[^⟩]+⟩",older_list)]
    old=[]
    for option in option_rows:
        if option=="none":
            old.append(None)
            continue
        row=re.fullmatch(r"some ⟨([^,]+), (none|some [^⟩]+)⟩",option)
        numerator=F(row[1].strip("()"))
        width=None if row[2]=="none" else F(row[2].removeprefix("some ").strip("()"))
        old.append((numerator,width))
    if old!=[aff.get(z) for z in range(1,51)]:
        raise ValueError("Emitted historical affinity options differ")
    print(f"{len(aff)} borrowed affinity values and their reported or missing widths checked.")
    print("1,830 archived central energies and 1,830 uncertainty fields verified against Lean source.")
    for (ordinary,mode),(n,left,right) in bounds.items():
        lo,hi=left[2 if mode=="central" else 4],right[2 if mode=="central" else 3]
        print(f"{'ordinary' if ordinary else 'all'}, {mode}: {n} rows, [{lo}, {hi}), "
              f"witnesses (Z={left[0]}, k={left[1]}) and (Z={right[0]}, k={right[1]}).")
    print(f"Missing uncertainty pairs: {len(gaps)}.")
    run(args.lean,audits)


if __name__=="__main__":
    main()
