NAMES = ["Promethium","Samarium","Europium","Gadolinium","Terbium"]


def table(path):
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def num(x):
    return format(Decimal(x),"f")


def load():
    raw=ARCHIVE.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=HASH:
        raise ValueError("Pinned archive digest mismatch")
    atoms=json.loads(gzip.decompress(raw),parse_float=Decimal)["records"][60:65]
    if [(a["Z"],a["name"]) for a in atoms]!=list(enumerate(NAMES,61)):
        raise ValueError("Wrong element records")
    af=table(LADDER/"affinities.csv")
    if [int(a["Z"]) for a in af]!=list(range(61,66)):
        raise ValueError("Affinity status keys differ")
    ies={}
    for a in atoms:
        if [r["q"] for r in a["thresholds"]]!=list(range(a["Z"])):
            raise ValueError("Incomplete charge keys")
        ies[a["name"]]=[(num(r["IE_eV"]),num(r["unc_eV"])) for r in a["thresholds"]]
    return ies,af


def powerset(seq):
    if not seq:
        return [[]]
    rest=powerset(seq[1:])
    return rest+[[seq[0]]+s for s in rest]


def as_lean_list(seq):
    if isinstance(seq,list):
        return "["+", ".join(as_lean_list(x) for x in seq)+"]"
    return str(seq)


def expected(levels):
    v=[(F(a),F(u)) for a,u in levels]
    reverse=[]
    touch=[]
    scale=[]
    for k,((a,u),(b,w)) in enumerate(zip(v,v[1:]),1):
        gap=b-w-a-u
        if gap<0:
            reverse.append(k)
        if gap==0:
            touch.append(k)
        scale.append(((b-a)/(u+w),k))
    first=sorted(scale)
    if first[0][0]>=first[1][0]:
        raise ValueError("Earliest contact scale is tied")
    patterns=[xs for xs in powerset(reverse) if not (13 in xs and 14 in xs)]
    return reverse,touch,patterns,first[0]


def generate(ies,af):
    out=["-- Generated by verify.py. Each pair is (central eV, quoted absolute uncertainty in eV).",
         "import JointDirection", "", "namespace ElementPaper.Batch13", "",
         "open ElementPaper.Batch12", "open VOTKP.NearestPair",
         "set_option maxRecDepth 16384", "set_option maxHeartbeats 12000000", ""]
    audits=["observedFilter","noConsecutiveReversal","onlyPossible","feasibleIff","smallerScaleStrict"]
    for z,(name,aff) in enumerate(zip(NAMES,af),61):
        vals=[f"({a}, {u})" for a,u in ies[name]]
        rev,touch,patterns,(scale,k)=expected(ies[name])
        out.extend([f"def {name} : List Reading :=","  ["+",\n   ".join(
                    ", ".join(vals[i:i+4]) for i in range(0,len(vals),4))+"]","",
                    f"theorem {name}Ordinary : {name}.length = {z} ∧",
                    f"    (faces {name}).all admitsInside = true ∧",
                    f"    (centralPairs {name}).all (fun p => decide (p.2/p.1 ≤ Batch11.nitrogen) &&",
                    "      !Batch11.outside p.1 p.2) = true := by decide +kernel","",
                    f"theorem {name}Directions : candidates {name} = {as_lean_list(rev)} ∧",
                    f"    contacts {name} = {as_lean_list(touch)} ∧",
                    f"    possible {name} = {as_lean_list(patterns)} ∧ realizedAll {name} = true ∧",
                    f"    firstScale {name} {k} ({scale.numerator}/{scale.denominator}) = true := by",
                    "  decide +kernel","",
                    f"theorem {name}Complete (keys : List Nat) :",
                    f"    (∃ ys, realizes {name} ys = true ∧ observed {name} ys = keys) ↔",
                    f"    keys ∈ {as_lean_list(patterns)} := by",
                    f"  rw [← {name}Directions.2.2.1]",
                    f"  exact feasibleIff (by decide +kernel) (by decide +kernel) {name}Directions.2.2.2.1 keys",""])
        audits.extend([name+"Ordinary",name+"Directions",name+"Complete"])
        if aff["EA_eV"]:
            out.extend([f"def {name}EA : Reading := ({aff['EA_eV']}, {aff['unc_eV']})",
                        f"theorem {name}Anion :",
                        f"    let f := face {name}EA {name}[0]!",
                        "    admitsOutside f = true ∧ chemistryOutside f = true ∧ Batch11.silicon < endpointLo f := by",
                        "  decide +kernel",""])
            audits.append(name+"Anion")
    sm=af[1]
    if sm["status"]!="measured-lower-bound" or af[0]["status"]!="theory-only":
        raise ValueError("Promethium or samarium sourced status changed")
    out.extend(["/-- Two hypothetical positive affinities illustrate the information content",
                "of the one-sided samarium measurement. Neither is asserted as its true EA. -/",
                "theorem samariumLowerBoundPermitsBoth :",
                "    let ie := Samarium[0]!.1",
                f"    ({sm['lower_bound_eV']}:Rat)<0.1 ∧ ({sm['lower_bound_eV']}:Rat)<1.2 ∧",
                "    (1.2:Rat)<ie ∧ Batch11.outside 0.1 ie = true ∧ Batch11.outside 1.2 ie = false := by",
                "  decide +kernel","",
                "def newOrdinary := ["+", ".join(NAMES)+"].flatMap centralPairs",
                "def throughTerbium := throughNeodymium ++ newOrdinary","",
                "theorem ordinaryCount : newOrdinary.length = 310 ∧ throughTerbium.length = 2080 := by",
                "  decide +kernel", "",
                "theorem windowHydrogenTerbium (c : Rat) : Batch11.Fits throughTerbium c ↔",
                "    Batch11.nitrogen ≤ c ∧ c < Batch11.cesium := by",
                "  constructor", "  · intro h", "    apply (windowHydrogenNeodymium c).mp",
                "    intro p hp", "    exact h p (List.mem_append_left newOrdinary hp)",
                "  · rintro ⟨hl,hu⟩ p hp",
                "    rcases List.mem_append.mp hp with old | fresh",
                "    · exact (windowHydrogenNeodymium c).mpr ⟨hl,hu⟩ p old",
                "    · have checks : newOrdinary.all (fun x => decide (x.2/x.1 ≤ Batch11.nitrogen) &&",
                "          !Batch11.outside x.1 x.2) = true := by decide +kernel",
                "      have h := List.all_eq_true.mp checks p fresh", "      simp at h",
                "      rw [h.2]", "      exact decide_eq_false (by grind)", ""])
    audits.extend(["samariumLowerBoundPermitsBoth","ordinaryCount","windowHydrogenTerbium"])
    out.extend(["#print axioms "+name for name in audits])
    out.extend(["","end ElementPaper.Batch13",""])
    return "\n".join(out),audits


def independent(source,ies,aff):
    raw=json.loads(gzip.decompress(ARCHIVE.read_bytes()),parse_float=F)["records"]
    printed=table(LADDER/"batch13_pm_tb.csv")
    expected_keys=[(z,k) for z in range(61,66) for k in range(z+1)]
    if [(int(r["Z"]),int(r["k"])) for r in printed]!=expected_keys:
        raise ValueError("Wrong CSV keys")
    for z,name in enumerate(NAMES,61):
        chunk=re.search(rf"def {name} : List Reading :=\s*\[(.*?)\]",source,re.S)[1]
        literals=[(F(a),F(u)) for a,u in re.findall(r"\(([\d.]+), ([\d.]+)\)",chunk)]
        expected_values=[(t["IE_eV"],t["unc_eV"]) for t in raw[z-1]["thresholds"]]
        if literals!=expected_values:
            raise ValueError(f"{name} energy/uncertainty mismatch")
    valid=0
    for r in printed:
        z,k=int(r["Z"]),int(r["k"])
        name=NAMES[z-61]
        x=F(ies[name][k-1][0]) if k else (F(aff[z-61]["EA_eV"]) if aff[z-61]["EA_eV"] else None)
        if x is None:
            if (r["IE_k (eV)"],r["z_k"],r["Gamma_k"])!=("","",""):
                raise ValueError("Spurious point affinity")
            continue
        if F(r["IE_k (eV)"])!=x:
            raise ValueError(f"Printed energy mismatch Z={z},k={k}")
        if k==z:
            if r["z_k"] or r["Gamma_k"]:
                raise ValueError("Spurious terminal ratio")
        else:
            y=F(ies[name][k][0])
            if (F(r["z_k"]),F(r["Gamma_k"]))!=(round(y/x,6),round((y-x)/(y+x),6)):
                raise ValueError(f"Printed ratio mismatch Z={z},k={k}")
            valid+=1
    print(f"315 archived energy and uncertainty fields match regenerated Lean literals. 320 CSV rows checked, including all {valid} ratio pairs.")
    budgets=[]
    for z,name in enumerate(NAMES,61):
        levels=[(F(a),F(u)) for a,u in ies[name]]
        for k,((a,u),(b,v)) in enumerate(zip(levels,levels[1:]),1):
            budgets.append(((b-a-abs(u-v))/min(u,v),z,k))
        rev,touch,sets,(scale,k)=expected(ies[name])
        print(f"{name}: reversal keys {rev}, contact-only keys {touch}, exact feasible subsets {sets}; earliest common-width contact k={k}, factor {scale}.")


    if sorted(budgets)[:2]!=[(F(9,7),63,14),(F(19,14),64,14)]:
        raise ValueError("Standardized differential-error minima differ")
    print("All 310 ordinary differential-error budgets checked; 9/7 is the unique first contact, Eu k=14; second is Gd k=14 at 19/14.")


def check_axioms(log,namespace,names):
    matches=re.findall(r"'"+re.escape(namespace)+r"\.(\w+)' depends on axioms: \[([^\]]+)\]",log)
    if [n for n,_ in matches]!=names:
        raise RuntimeError("Incomplete axiom output\n"+log)
    for n,ax in matches:
        if set(re.split(r",\s*",ax))-{"propext","Classical.choice","Quot.sound"}:
            raise ValueError(f"Unexpected axiom at {n}: {ax}")
    print(log.rstrip())


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lean",default="lean")
    parser.add_argument("--generate",action="store_true")
    args=parser.parse_args()
    ies,aff=load()
    src,audits=generate(ies,aff)
    target=HERE/"PromethiumTerbium.lean"
    if args.generate:
        target.write_text(src)
    if target.read_text()!=src:
        raise ValueError("Regenerated source differs")
    independent(src,ies,aff)
    files=[PAPER/"batch10/nearest_lean/MarginBounds.lean",PAPER/"batch11/lean/Batch11Kernel.lean",
           PAPER/"batch11/lean/AntimonyCesium.lean",PAPER/"batch12/lean/Batch12Bounds.lean",
           PAPER/"batch12/lean/BariumNeodymium.lean",HERE/"JointDirection.lean",target]
    print(subprocess.check_output([args.lean,"--version"],text=True).strip(),flush=True)
    with tempfile.TemporaryDirectory() as td:
        tmp=Path(td)
        env=dict(os.environ,LEAN_PATH=td)
        for p in files:
            shutil.copyfile(p,tmp/p.name)
            run=subprocess.run([args.lean,"-j1","-o",p.stem+".olean",p.name],cwd=tmp,env=env,capture_output=True,text=True)
            if run.returncode:
                raise RuntimeError(run.stdout+run.stderr)
        check_axioms(run.stdout,"ElementPaper.Batch13",audits)
        extra=HERE/"SharedError.lean"
        shutil.copyfile(extra,tmp/extra.name)
        more_names=re.findall(r"^#print axioms (\w+)",extra.read_text(),re.M)
        out=subprocess.run([args.lean,"-j1","-o","SharedError.olean",extra.name],
                           cwd=tmp,env=env,capture_output=True,text=True)
        if out.returncode:
            raise RuntimeError(out.stdout+out.stderr)
        check_axioms(out.stdout,"ElementPaper.Batch13.SharedError",more_names)
        for title,claim in [
                ("every samarium sign fixed","candidates Samarium = []"),
                ("samarium can reverse steps 13 and 14 together","[13,14] ∈ possible Samarium"),
                ("all terbium reversals independent","(possible Terbium).length = 8"),
                ("gadolinium guaranteed forward at step 15","15 ∉ contacts Gadolinium"),
                ("no contact at the critical standardized error difference",
                 "SharedError.atLimit Europium none = true")]:
            (tmp/"Wrong.lean").write_text(f"import SharedError\nopen ElementPaper.Batch13\nexample : {claim} := by decide +kernel\n")
            bad=subprocess.run([args.lean,"-j1","Wrong.lean"],cwd=tmp,env=env,text=True,capture_output=True)
            if bad.returncode==0 or "error: Tactic `decide`" not in bad.stdout:
                raise RuntimeError("False control inconclusive\n"+bad.stdout+bad.stderr)
            print("Rejected: "+title)
    print(f"{len(audits)+len(more_names)} axiom audits passed, five false controls rejected.")


if __name__=="__main__":
    main()
