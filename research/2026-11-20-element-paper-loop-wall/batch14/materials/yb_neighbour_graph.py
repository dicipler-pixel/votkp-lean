"""Exact fractional-coordinate shortest-walk controls for four elemental Yb phases.

The hP3 basis is the published P6_222 3c site (1/2,0,0) and its orbit.
The reciprocal orientation is generated by one Cartesian reflection.
All walks of length three count, including return links and repeated sites.
"""
from collections import Counter
import csv
from fractions import Fraction as F
from itertools import product
from pathlib import Path

HERE = Path(__file__).resolve().parent
ZERO = (F(0),) * 3
HALF = F(1, 2)
BASES = {
    'cI2': (ZERO, (HALF, HALF, HALF)),
    'cF4-II': (ZERO, (0, HALF, HALF), (HALF, 0, HALF), (HALF, HALF, 0)),
    'hP2': (ZERO, (F(2, 3), F(1, 3), HALF)),
    'hP3': ((HALF, 0, 0), (HALF, HALF, F(1, 3)), (0, HALF, F(2, 3))),
}
ASPECT = {'cI2': 1, 'cF4-II': 1, 'hP2': F(8, 5), 'hP3': F(7, 3)}


def determinant(a, b, c):
    return sum(a[i] * (b[(i+1)%3] * c[(i+2)%3] - b[(i+2)%3] * c[(i+1)%3])
               for i in range(3))


def metric_coefficients(e, hexagonal):
    x, y, z = e
    return x*x + y*y - (x*y if hexagonal else 0), z*z


def displacements(phase, start=0, mirror=False):
    hexagonal = phase.startswith('hP')
    basis = BASES[phase]
    result = []
    for target, site in enumerate(basis):
        for t in product(range(-2, 3), repeat=3):
            edge = tuple(site[j] - basis[start][j] + t[j] for j in range(3))
            if edge == ZERO:
                continue
            x, y, z = edge
            if mirror:
                edge = ((x-y if hexagonal else x), -y, z)
            b, l = metric_coefficients(edge, hexagonal)
            result.append((target, edge, b, l))
    return result


def nearest_graph(phase, mirror=False):
    graph = {}
    for start in range(len(BASES[phase])):
        candidates = displacements(phase, start, mirror)
        q = ASPECT[phase]
        d2 = min(b + l*q*q for _, _, b, l in candidates)
        graph[start] = [(t, e) for t, e, b, l in candidates if b + l*q*q == d2]
    return graph


def distribution(graph, start, upward=False):
    hist = Counter()
    for i, a in graph[start]:
        for j, b in graph[i]:
            for k, c in graph[j]:
                if upward and min(a[2], b[2], c[2]) <= 0:
                    continue
                chi = determinant(a, b, c)
                rev = [tuple(-u for u in e) for e in (c,b,a)]
                assert determinant(*rev) == chi
                hist[F(chi)] += 1
    return hist


def screw_check():
    xyz = (HALF, F(0), F(0))
    orbit = [xyz]
    for _ in range(6):
        x, y, z = orbit[-1]
        orbit.append((x-y, x, z+F(1,3)))
    offsets = [tuple(q-p for p,q in zip(s,t)) for s,t in zip(orbit,orbit[1:])]
    assert determinant(*offsets[:3]) == F(1,12)
    assert tuple(x-y for x,y in zip(orbit[3],orbit[0])) == (-1,0,1)
    assert tuple(x-y for x,y in zip(orbit[6],orbit[0])) == (0,0,2)
    assert len({tuple(x%1 for x in p) for p in orbit[:-1]}) == 3


def main():
    rows = []
    for phase in BASES:
        for upward in ([False, True] if phase == 'hP3' else [False]):
            for mirror in ([False, True] if phase == 'hP3' else [False]):
                graph = nearest_graph(phase, mirror)
                all_starts = [distribution(graph,s,upward) for s in graph]
                h = all_starts[0]
                assert all(h == other for other in all_starts[1:])
                count = sum(h.values())
                mean = sum(x*n for x,n in h.items())/count
                m3 = sum(x**3*n for x,n in h.items())/count
                assert mean == 0
                expected = F(1,288) if upward else F(1,1152)
                assert m3 == (expected*(1 if mirror else -1) if phase=='hP3' else 0)
                for x,n in sorted(h.items()):
                    rows.append(dict(phase=phase, hand='reflected' if mirror else 'as_specified',
                                     walks='positive_z' if upward else 'all',
                                     nearest_neighbours=len(graph[0]), determinant_over_Vcell=x,
                                     count=n, total=count, mean_over_Vcell=mean,
                                     M3_over_Vcell_cubed=m3,
                                     M3_over_atomic_volume_cubed=m3*len(graph)**3))
    screw_check()
    with (HERE/'yb_handedness.csv').open('w') as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]),lineterminator='\n')
        w.writeheader()
        w.writerows(rows)
    print('Three inversion/mirror-symmetric phase controls and two hP3 hands passed;'
          ' all starting sites and reversed walks checked; screw closure checked.')


if __name__ == '__main__':
    main()
