"""Generate strict ordinary wall certificates from the pinned VOTKP archive."""

import argparse
import gzip
import hashlib
import json
from decimal import Decimal
from pathlib import Path


PIN = "cae5f49b774583fbc376fe05484514a287469ea2"
ARCHIVE_SHA256 = "75e67478d9a22ef85fa2d3f6ac36ad2860c6f8f62215127c558438a2cb53f62c"
# Expected strictly outside ordinary rung indices (1-based). The proof checks
# these independently in Lean, including strict inside on every remaining rung.
EXPECTED_OUTSIDE = {"Rb": [1]}


def literal(value):
    return format(value, "f")


def build(archive):
    raw = archive.read_bytes()
    if hashlib.sha256(raw).hexdigest() != ARCHIVE_SHA256:
        raise ValueError(f"Archive does not match commit {PIN}")
    entries = json.loads(gzip.decompress(raw), parse_float=Decimal)["records"]
    indexed = {row["Z"]: row for row in entries}

    def energies(number):
        thresholds = indexed[number]["thresholds"]
        if [row["q"] for row in thresholds] != list(range(number)):
            raise ValueError(f"Missing or reordered charge at Z={number}")
        return [literal(Decimal(row["IE_eV"])) for row in thresholds]

    parts = ["""-- Generated by generate_lean.py; central energies (eV) from VOTKP at
-- cae5f49b774583fbc376fe05484514a287469ea2. No measurement-uncertainty claim.
import Std

namespace VOTKP.ElementBatches7And8

/-- Both input energies must be positive and strictly increasing. The sign of
2(b−a)² − (a+b)² is the sign of Γ² − 1/2. A boundary tie therefore fails
both strict tests. k=1 is the first ordinary rung; anion EAs are excluded. -/
def checkWall (a b : Rat) (outside : Bool) : Bool :=
  let p := 2 * (b - a)^2
  let q := (a + b)^2
  decide (0 < a ∧ a < b) && (if outside then decide (q < p) else decide (p < q))

def checkLadder (energies : List Rat) (outside : List Nat) : Bool :=
  let pairs := energies.zip energies.tail
  pairs.zipIdx.all fun ((a, b), index) => checkWall a b (outside.contains (index + 1))

def reflection (a b : Rat) : Rat := (b - a) / (a + b)
"""]
    names = []
    for number in range(31, 41):
        symbol = indexed[number]["symbol"]
        values = energies(number)
        chunks = [", ".join(values[i:i+6]) for i in range(0, len(values), 6)]
        outside = str(EXPECTED_OUTSIDE.get(symbol, []))
        theorem = f"ordinary_{symbol}"
        names.append(theorem)
        parts.append(f"def energies{symbol} : List Rat :=\n  [" + ",\n   ".join(chunks) + "]\n")
        parts.append(f"theorem {theorem} :\n"
                     f"    energies{symbol}.length = {number} ∧ checkLadder energies{symbol} {outside} = true := by\n"
                     "  decide +kernel\n")
    ni = energies(28)
    for k in (20, 21):
        a, b = ni[k-1:k+1]
        # Bounds are centered on the six-place half-up results. The false
        # control checks a different six-place display interval from the review.
        good_z, good_g, wrong_z = {
            20: ("1.068044", "0.032902", "1.063183"),
            21: ("1.069397", "0.033535", "1.074286"),
        }[k]
        theorem = f"nickel_rung_{k}_display"
        names.append(theorem)
        parts.append(f"theorem {theorem} :\n"
                     f"    let z := ({b} / {a} : Rat)\n"
                     f"    let g := reflection {a} {b}\n"
                     f"    ({good_z} - 0.0000005 < z ∧ z < {good_z} + 0.0000005) ∧\n"
                     f"    ({good_g} - 0.0000005 < g ∧ g < {good_g} + 0.0000005) ∧\n"
                     f"    ¬ ({wrong_z} - 0.0000005 ≤ z ∧ z ≤ {wrong_z} + 0.0000005) := by\n"
                     "  decide +kernel\n")
    # The right-angle mixed rule at positive forward steps, using the squared
    # disk criterion, is open iff (za-1)^2(zb-1)^2 > 16 za zb.
    carbon = energies(6)[3:5]
    nitrogen = energies(7)[4:6]
    rb = energies(37)[:2]
    sr = energies(38)[1:3]
    parts.append("""/-- Sign of the squared two-face opening condition for forward ratios.
Positive is open, negative closes, zero is the ideal-boundary case. -/
def mixedScore (a b c d : Rat) : Rat :=
  (b - a)^2 * (d - c)^2 - 16 * a * b * c * d

/-- Clearing the two positive squared denominators of Γ₁² + Γ₂² − 1. -/
theorem mixed_reflection_numerator (a b c d : Rat) :
    mixedScore a b c d =
    (b-a)^2 * (d+c)^2 + (d-c)^2 * (b+a)^2 - (b+a)^2*(d+c)^2 := by
  unfold mixedScore
  grind
theorem mixed_equal_face (a b : Rat) :
    mixedScore a b a b = (2*(b-a)^2-(a+b)^2)*(a+b)^2 := by
  unfold mixedScore
  grind
""")
    names.extend(["mixed_reflection_numerator", "mixed_equal_face"])
    for label, first, second, expected in [
        ("carbon_nitrogen", carbon, nitrogen, ">"),
        ("rubidium_strontium", rb, sr, "<"),
    ]:
        theorem = f"mixed_{label}"
        names.append(theorem)
        parts.append(f"theorem {theorem} : mixedScore {' '.join(first + second)} {expected} 0 := by\n  decide +kernel\n")
    controls = {
        "no_all_inside_Rb": "checkLadder energiesRb [] = false",
        "no_outside_Sr_kr_opening": "checkLadder energiesSr [2] = false",
        "mistyped_ni20_fails_rounding": "¬ (1.0680435 < (1750 / 1646 : Rat) ∧ (1750 / 1646 : Rat) < 1.0680445)",
        "no_open_rubidium_strontium": f"¬ (mixedScore {' '.join(rb + sr)} > 0)",
    }
    for name, proposition in controls.items():
        parts.append(f"theorem {name} : {proposition} := by\n  decide +kernel\n")
        names.append(name)
    parts.extend(f"#print axioms {name}" for name in names)
    parts.append("\nend VOTKP.ElementBatches7And8\n")
    return "\n".join(parts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(build(args.archive), encoding="utf-8")
