# SCRIPT: VOTKP-OPENING-MAP-LEAN-GEN-01
# Writes OpeningMap.lean: one wall certificate per noble-core opening ratio in the archive
# (He, Ne, Ar, Kr, Xe, Rn cores), plus the Sc-Mn ordinary ladders, Rb/Sr and the Fr straddle.
# Energies are copied verbatim from data/element_thresholds_20261011.json.gz as decimal literals.
import gzip, json, math, sys
from decimal import Decimal as D
d=json.load(gzip.open(sys.argv[1])); rec={r['Z']:r for r in d['records']}
w=3+2*math.sqrt(2)
def lit(x):
    v=x if isinstance(x,D) else D(repr(float(x)))
    return format(v,'f')
L=['/-','# SCRIPT: VOTKP-OPENING-MAP-01 (generated by gen_opening_map_lean.py)',
'The noble-core opening map from data/element_thresholds_20261011.json.gz, using the encoded',
'reference thresholds. For a core of N electrons and element Z the opening is IE(q+1)/IE(q) with',
'q = Z - N - 1: the last removal above the core, then the first removal from it.','-/','import LoopWall','']
cores=[(2,'He'),(10,'Ne'),(18,'Ar'),(36,'Kr'),(54,'Xe'),(86,'Rn')]
summary=[]
for N,name in cores:
    outs=[];ins=[]
    for Z in range(N+1,119):
        th={t['q']:t['IE_eV'] for t in rec[Z]['thresholds']}; q=Z-N-1
        if q in th and q+1 in th:
            z=th[q+1]/th[q]; s=rec[Z]['symbol']
            expr=f'({lit(th[q+1])} / {lit(th[q])} : Rat)'
            (outs if z>w else ins).append((s,expr))
    if outs:
        L.append(f'/-- {name}-like core: outside the wall for '+', '.join(s for s,_ in outs)+'. -/')
        L.append(f'theorem core{name}_outside :')
        L.append('    '+' ∧\n    '.join(f'outside {e}' for _,e in outs)+' := by')
        L.append('  unfold outside; '+('refine ⟨'+', '.join(['?_']*len(outs))+'⟩ <;> ' if len(outs)>1 else '')+'grind'); L.append('')
    # inside, chunked
    for i in range(0,len(ins),10):
        ch=ins[i:i+10]
        L.append(f'/-- {name}-like core: inside the wall for '+', '.join(s for s,_ in ch)+'. -/')
        L.append(f'theorem core{name}_inside_{i//10+1} :')
        L.append('    '+' ∧\n    '.join(f'inside {e}' for _,e in ch)+' := by')
        L.append('  unfold inside; '+('refine ⟨'+', '.join(['?_']*len(ch))+'⟩ <;> ' if len(ch)>1 else '')+'grind'); L.append('')
    summary.append((name,len(outs),len(ins)))
# Sc..Sn ordinary ladders: every step inside except a noble-core opening (certified above)
for Z in range(21,51):
    th=sorted(rec[Z]['thresholds'],key=lambda t:t['q']); s=rec[Z]['symbol']
    pairs=[(a,b) for a,b in zip(th,th[1:]) if b['q']==a['q']+1]
    isout=lambda a,b: (lambda z: z>3 and (z-3)**2>8)(b['IE_eV']/a['IE_eV'])
    skip=[a['q']+1 for a,b in pairs if isout(a,b)]
    ex=[f"inside ({lit(b['IE_eV'])} / {lit(a['IE_eV'])} : Rat)" for a,b in pairs if not isout(a,b)]
    note=''.join(f', except the step from removal {q} to removal {q+1} (the noble-core opening, certified in its core theorem)' for q in skip)
    L.append(f'/-- Every ordinary step of the {s} ladder ({len(ex)} steps) is inside the wall{note}. -/')
    L.append(f'theorem ladder_{s}_all_inside :'); L.append('    '+' ∧\n    '.join(ex)+' := by')
    L.append('  unfold inside; refine ⟨'+', '.join(['?_']*len(ex))+'⟩ <;> grind'); L.append('')
# Fr straddle
fr={t['q']:t for t in rec[87]['thresholds']}
a,b=fr[0],fr[1]
L+=['/-- Francium: the encoded central opening ratio is inside, but the input interval straddles the',
f"wall: IE1 = {a['IE_eV']}({a['unc_eV']}) eV, IE2 = {b['IE_eV']}({b['unc_eV']}) eV ({b['grade']}). -/",
'theorem francium_straddles :',
f"    inside ({lit(b['IE_eV'])} / {lit(a['IE_eV'])} : Rat) ∧",
f"    inside ({lit(D(repr(b['IE_eV']))-D(repr(b['unc_eV'])))} / {lit(D(repr(a['IE_eV']))+D(repr(a['unc_eV'])))} : Rat) ∧",
f"    outside ({lit(D(repr(b['IE_eV']))+D(repr(b['unc_eV'])))} / {lit(D(repr(a['IE_eV']))-D(repr(a['unc_eV'])))} : Rat) := by",
'  unfold inside outside; refine ⟨?_, ?_, ?_⟩ <;> grind','']
open('OpeningMap.lean','w').write('\n'.join(L))
print(summary)
