# SCRIPT: CHECK-GRAVITY-03-GRAM-SUMRULE
# Gravity paper against the Loop Wall element paper.
# Connection checked: one identity appears in both papers under four names.
#  E1 (element, spinor recovery) peel identity:  i^T A^2 i - (i^T A i)^2 = (Q A i)^dag (Q A i),  Q = 1 - i i^dag
#  E2 (element, Section 7) junction sum rule:   sum_{j != i} ||P_ij||^2 = Tr(C_i - C_i^2)
#  E3 (element, Section 7) localization tensor: Var(X) = Tr(P X (1-P) X) = 1/2 sum_ij ||P_ij||^2 (x_i - x_j)^2
#  G1 (gravity final_v3 Prop 20 = Edition 6/7 Theorem 5): dP = X + Y, g = Re 1/2 Tr(XY + YX); P = P^dag => Y = X^dag, Gram, PSD
#  G2 (gravity Edition 7 Prop 33): for C = [H,P], q(C) = -Tr(B B^dag), q(-iC) = +Tr(B B^dag), q(X) = 1/2 Re Tr X^2
#  G3 (gravity final_v3 Result 22): region fluctuation F_A = Tr Pi_A (1 - Pi_A), Pi_A = P_A Pi P_A
# Claim: E2 is E1 with A = P and the site isometry; E3 is G1/G2 for the unitary tangent generated by
# a site-constant position X; E2 is G3 for a one-site region; G2's positive sign is G1's Gram case.
#
# WHY THIS PROVES WHAT IT CLAIMS. Each line below evaluates both sides of an asserted identity on
# random matrices (many seeds, several sizes) and on the half-filled chain. An identity that is
# false fails at generic random input with probability one, so residuals at roundoff on random
# input confirm the algebra (the algebra is also given in the report). Kill condition (written
# before the run): any residual above 1e-10 relative.
import numpy as np
rng = np.random.default_rng(20261121)

def rand_proj(n, k):
    M = rng.normal(size=(n, n)) + 1j * rng.normal(size=(n, n))
    Qm, _ = np.linalg.qr(M); V = Qm[:, :k]; return V @ V.conj().T
def herm(n):
    M = rng.normal(size=(n, n)) + 1j * rng.normal(size=(n, n)); return (M + M.conj().T) / 2
q = lambda X: 0.5 * np.real(np.trace(X @ X))

worst = {k: 0.0 for k in ['E1', 'E2=E1(A=P)', 'E3', 'E3=G2', 'G1 Gram', 'G2 sign', 'E2=G3', 'blocks']}
for trial in range(200):
    n = int(rng.integers(4, 11)); k = int(rng.integers(1, n)); m = int(rng.integers(1, n))
    P = rand_proj(n, k); A = herm(n)
    # E1 with a random m-dimensional layer isometry
    iso = np.linalg.qr(rng.normal(size=(n, m)) + 1j * rng.normal(size=(n, m)))[0]
    Qc = np.eye(n) - iso @ iso.conj().T
    lhs = iso.conj().T @ A @ A @ iso - (iso.conj().T @ A @ iso) @ (iso.conj().T @ A @ iso)
    rhs = (Qc @ A @ iso).conj().T @ (Qc @ A @ iso)
    worst['E1'] = max(worst['E1'], np.abs(lhs - rhs).max() / np.abs(lhs).max())
    # E2: sites = single basis vectors (one orbital per site) and also 2-orbital sites
    for so in (1, 2):
        if n % so: continue
        ns = n // so
        for s in range(ns):
            idx = slice(s * so, (s + 1) * so)
            Ci = P[idx, idx]
            lhs2 = np.real(np.trace(Ci - Ci @ Ci))
            rhs2 = sum(np.linalg.norm(P[idx, t * so:(t + 1) * so]) ** 2 for t in range(ns) if t != s)
            # E1 with A = P and iso = site isometry gives Ci - Ci^2 = sum_j P_ij P_ji
            e = np.zeros((n, so), complex); e[idx, :] = np.eye(so)
            Qs = np.eye(n) - e @ e.conj().T
            rhs1 = np.real(np.trace((Qs @ P @ e).conj().T @ (Qs @ P @ e)))
            worst['E2=E1(A=P)'] = max(worst['E2=E1(A=P)'], abs(lhs2 - rhs2) + abs(lhs2 - rhs1))
            # G3 for the one-site region: F_A = Tr Pi_A(1-Pi_A) with Pi_A = P_A P P_A
            PA = e @ e.conj().T; PiA = PA @ P @ PA
            worst['E2=G3'] = max(worst['E2=G3'], abs(np.real(np.trace(PiA - PiA @ PiA)) - lhs2))
    # E3: site-constant position X (one orbital per site, coordinates x_i)
    x = rng.normal(size=n); X = np.diag(x)
    var = np.real(np.trace(P @ X @ (np.eye(n) - P) @ X))
    mom = 0.5 * sum(abs(P[i, j]) ** 2 * (x[i] - x[j]) ** 2 for i in range(n) for j in range(n))
    worst['E3'] = max(worst['E3'], abs(var - mom) / abs(var))
    # G2 with H = X: unitary tangent -i[X,P] has q = +Tr(BB^dag) = Var(X); similarity tangent [X,P] has q = -Var(X)
    Cm = X @ P - P @ X
    worst['E3=G2'] = max(worst['E3=G2'], abs(q(-1j * Cm) - var) / var + abs(q(Cm) + var) / var)
    # G1: unitary family P(t) = e^{-iXt} P e^{iXt}: dP = -i[X,P]; X1 = P dP (1-P), Y1 = (1-P) dP P; Y1 = X1^dag
    dP = -1j * Cm; X1 = P @ dP @ (np.eye(n) - P); Y1 = (np.eye(n) - P) @ dP @ P
    gpair = np.real(0.5 * np.trace(X1 @ Y1 + Y1 @ X1))
    worst['G1 Gram'] = max(worst['G1 Gram'], np.abs(Y1 - X1.conj().T).max() + abs(gpair - q(dP)) + abs(gpair - var))
    # G2 sign for a general Hermitian H: q(C) = -Tr(BB^dag), q(-iC) = +Tr(BB^dag), B = P H (1-P)
    H = herm(n); C2 = H @ P - P @ H; B = P @ H @ (np.eye(n) - P)
    t = np.real(np.trace(B @ B.conj().T))
    worst['G2 sign'] = max(worst['G2 sign'], abs(q(C2) + t) / t + abs(q(-1j * C2) - t) / t)
    # the same Tr(BB^dag) is the peel defect of E1 with A = H and iso spanning Ran P (zero-time memory weight)
    w, V = np.linalg.eigh(P); Vr = V[:, w > 0.5]
    Qr = np.eye(n) - Vr @ Vr.conj().T
    peel_def = np.real(np.trace((Qr @ H @ Vr).conj().T @ (Qr @ H @ Vr)))
    worst['blocks'] = max(worst['blocks'], abs(peel_def - t) / t)
for kk, v in worst.items(): print(f'{kk:14s} worst residual {v:.2e}')

# half-filled tight-binding chain (periodic, L sites): nearest share 8/pi^2 (element check) and
# region fluctuation growth: gapless (log) versus gapped dimerised chain (saturates), the same
# contrast as gravity Result 22 and the element paper's rubidium-versus-krypton spread.
def chain_P(L, delta):
    H = np.zeros((L, L))
    for i in range(L):
        t = 1 + (delta if i % 2 == 0 else -delta)
        H[i, (i + 1) % L] = H[(i + 1) % L, i] = -t
    w, V = np.linalg.eigh(H); occ = V[:, :L // 2]; return occ @ occ.T
L = 2002   # L/2 odd -> nondegenerate half filling for the periodic chain
P0 = chain_P(L, 0.0); P1 = chain_P(L, 0.4)
i = L // 2
budget = P0[i, i] - P0[i, i] ** 2
near = P0[i, i - 1] ** 2 + P0[i, i + 1] ** 2
print('half-filled chain nearest share =', round(near / budget, 6), ' 8/pi^2 =', round(8 / np.pi ** 2, 6))
for ell in (8, 16, 32, 64, 128):
    out = []
    for Pm in (P0, P1):
        S = slice(i, i + ell); PiA = Pm[S, S]
        out.append(np.trace(PiA - PiA @ PiA))
    print(f'region size {ell:4d}: F_A gapless = {out[0]:.5f}   F_A gapped = {out[1]:.5f}')
